import { test } from "@playwright/test";
import { ADDR, open } from "../e2e/helpers";

const out = (n: string) => ({ path: `screenshots/${n}.png` });
test.describe.configure({ mode: "serial" });

test("capture 12 screens", async ({ page }) => {
  test.setTimeout(120_000);
  await open(page, "/");
  await page.waitForTimeout(800);
  await page.screenshot(out("01-landing"));
  await page.getByTestId("menu-button").click();
  await page.waitForTimeout(500);
  await page.screenshot(out("02-menu"));
  await page.keyboard.press("Escape");
  await page.getByTestId("connect-button").click();
  await page.waitForTimeout(600);
  await page.screenshot(out("03-connect"));
  await page.keyboard.press("Escape");
  await page.getByTestId("hero-cta").click();
  await page.getByTestId("amount-input").fill("0.01");
  await page.screenshot(out("04-send"));
  await page.getByTestId("address-input").fill(ADDR.critical);
  await page.getByTestId("check-risk").click();
  await page.waitForTimeout(250);
  await page.screenshot(out("05-checking"));
  await page.getByTestId("presend-alert").waitFor();
  await page.waitForTimeout(500);
  await page.screenshot(out("06-alert"));
  await page.getByTestId("alert-cancel").click();
  await page.locator("[data-sonner-toast]").first().waitFor();
  await page.evaluate(() => document.querySelectorAll("[data-sonner-toast]").forEach((t) => t.remove()));
  await page.getByRole("button", { name: "Open analysis" }).click();
  await page.waitForTimeout(1000);
  await page.screenshot({ ...out("07-analysis"), fullPage: true });
  await page.getByRole("button", { name: "Risk details" }).click();
  await page.waitForTimeout(1000);
  await page.screenshot({ ...out("08-details"), fullPage: true });
  await page.evaluate(() => window.history.pushState({}, "", "/preview"));
  await page.evaluate(() => window.dispatchEvent(new PopStateEvent("popstate")));
  await page.waitForTimeout(600);
  await page.screenshot(out("09-preview"));
  await page.evaluate(() => { window.history.pushState({}, "", "/consult"); window.dispatchEvent(new PopStateEvent("popstate")); });
  await page.getByRole("button", { name: "What is address poisoning?" }).click();
  await page.waitForTimeout(900);
  await page.screenshot(out("10-consult"));
  await page.getByTestId("bottom-nav").getByRole("link", { name: "History" }).click();
  await page.waitForTimeout(400);
  await page.screenshot(out("11-history"));
  await page.getByTestId("bottom-nav").getByRole("link", { name: "Settings" }).click();
  await page.waitForTimeout(400);
  await page.screenshot(out("12-settings"));
});
